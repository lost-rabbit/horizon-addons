--[[
* Is this name a known notorious monster? Zone-independent on purpose: the
* roster is an identity check, and a mob's name is unique enough for that.
* Zone still gates the TIMER lookup in M.Find, where intervals differ.
--]]
function M.IsNM(name)
    if (name == nil) then return false; end
    return M.roster[name:lower():gsub('^the ', '')] ~= nil;
end

--[[
* Home zone for a known NM, or nil. Useful for sanity-checking a match: if
* you are in Castle Oztroja and something claims to be Leaping Lizzy, the
* chat line was mis-parsed.
--]]
function M.HomeZone(name)
    if (name == nil) then return nil; end
    return M.roster[name:lower():gsub('^the ', '')];
end


--[[
* Lottery chance per placeholder death, as a percentage, or nil. From LSB's
* phOnDespawn argument 3 - the wiki publishes this for almost nothing.
--]]
function M.PopChance(mobName)
    local e = M.Find(mobName);
    return (e ~= nil) and e.pop or nil;
end

--[[
* Which NM does this placeholder roll for? nil if it is not a placeholder in
* the current zone.
--]]
function M.PHFor(mobName)
    local e = M.Find(mobName);
    return (e ~= nil) and e.nm or nil;
end

return M;
