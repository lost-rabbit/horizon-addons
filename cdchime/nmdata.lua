--[[
* Current zone name, lowercased. Empty string if it cannot be resolved (during
* a zone transition the party record is briefly unusable).
--]]
function M.Zone()
    local ok, name = pcall(function()
        local id = AshitaCore:GetMemoryManager():GetParty():GetMemberZone(0);
        local s = AshitaCore:GetResourceManager():GetString('zones.names', id);
        if (type(s) ~= 'string') then return ''; end
        return s:gsub('%z', ''):lower();
    end);
    if (not ok) or (name == nil) then return ''; end
    return name;
end

--[[
* Look up a mob in the CURRENT zone. Returns the entry table or nil.
*
* Zone-scoped on purpose: mob names repeat across the world and the intervals
* do not. A bare name lookup would happily hand South Gustaberg's numbers to a
* same-named mob three zones away.
--]]
function M.Find(mobName)
    if (mobName == nil) or (mobName == '') then return nil; end
    local z = M.zones[M.Zone()];
    if (z == nil) then return nil; end
    return z[mobName:lower()];
end

function M.PH(mobName)
    local e = M.Find(mobName);
    return (e ~= nil) and e.ph or nil;
end

function M.CD(mobName)
    local e = M.Find(mobName);
    return (e ~= nil) and e.cd or nil;
end

