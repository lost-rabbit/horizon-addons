--[[
* nmdata.lua - researched respawn/cooldown numbers, keyed by ZONE + MOB.
*
* WHY THIS EXISTS
*   phtimer's auto-register has to guess an interval on a mob's first kill,
*   and a flat guess is wrong nearly everywhere: Castle Oztroja placeholders
*   are 16 minutes, South Gustaberg's Rock Lizards are 5m30s. Same guess for
*   both is useless. This table lets the first kill use the real number.
*
* WHY IT IS BAKED IN RATHER THAN FETCHED
*   Ashita ships LuaSocket, so an addon *could* hit the wiki at runtime. It
*   should not: an HTTP call inside d3d_present blocks the frame, the Horizon
*   wiki times out for minutes at a stretch (observed repeatedly 2026-08-25),
*   and an addon making outbound calls is a rules question nobody needs. These
*   numbers were read off the wiki offline and pasted here. Re-check them if
*   Horizon rebases again.
*
* ZONE MATCHING
*   Zone comes from AshitaCore:GetMemoryManager():GetParty():GetMemberZone(0)
*   resolved through the resource manager - your own party record, NOT an
*   entity-table scan. Keys are lowercase zone names.
*
* FIELDS
*   ph   placeholder respawn, seconds - the countdown to your next lottery roll
*   cd   NM post-kill cooldown, seconds - dead time when no pop is possible
*   note provenance, so a wrong number can be traced instead of trusted
--]]

